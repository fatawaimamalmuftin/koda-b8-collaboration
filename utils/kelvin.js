function kelvinToCelcius(value) {
  return value + 273.15;
}
function kelvinToRankie(value) {
  return (value + 273.15) * 1.8;
}
function kelvintoFahrenheit(value) {
  return (value * 9) / 5 + 32;
}

module.exports = {
  kelvinToCelcius,
  kelvinToRankine,
  kelvinToFahrenheit,
};
